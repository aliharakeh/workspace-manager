/**
 * compile.ts — production single-binary build.
 *
 * Entry: `bun run compile`
 *
 * 1. Builds the Vite frontend → `dist/`
 * 2. Generates `server/embedded-assets.ts` with file embeds for `dist/` + `drizzle/`
 * 3. Compiles `server/index.ts` into `release/app-runner` (`.exe` on Windows)
 * 4. Restores the empty embeds stub so day-to-day `bun` runs keep using disk paths
 */
import { readdirSync, writeFileSync } from "node:fs"
import { join, relative } from "node:path"

const ROOT = join(import.meta.dir, "..")
const EMBEDS_PATH = join(ROOT, "server", "embedded-assets.ts")
const OUTFILE = join(ROOT, "release", "app-runner")

const STUB = `/**
 * Populated by \`bun run compile\` with \`with { type: "file" }\` imports so the
 * frontend and drizzle migrations ship inside the standalone binary.
 * Empty in normal \`bun\` / \`vite\` workflows — those read from disk instead.
 */
export const staticFiles: Record<string, string> = {}
export const migrationFiles: Record<string, string> = {}
`

function walkFiles(dir: string): string[] {
  const out: string[] = []
  for (const ent of readdirSync(dir, { withFileTypes: true })) {
    const full = join(dir, ent.name)
    if (ent.isDirectory()) out.push(...walkFiles(full))
    else out.push(full)
  }
  return out
}

function toPosix(path: string) {
  return path.replaceAll("\\", "/")
}

function genEmbeds() {
  const distDir = join(ROOT, "dist")
  const drizzleDir = join(ROOT, "drizzle")

  const staticPaths = walkFiles(distDir)
  const migrationPaths = walkFiles(drizzleDir)

  const lines: string[] = [
    "// Generated by scripts/compile.ts — do not edit",
    "",
  ]

  const staticEntries: string[] = []
  staticPaths.forEach((abs, i) => {
    const relFromServer = toPosix(relative(join(ROOT, "server"), abs))
    const key = toPosix(relative(distDir, abs))
    lines.push(`import s${i} from "${relFromServer}" with { type: "file" }`)
    staticEntries.push(`  ${JSON.stringify(key)}: s${i},`)
  })

  const migrationEntries: string[] = []
  migrationPaths.forEach((abs, i) => {
    const relFromServer = toPosix(relative(join(ROOT, "server"), abs))
    const key = toPosix(relative(drizzleDir, abs))
    lines.push(`import m${i} from "${relFromServer}" with { type: "file" }`)
    migrationEntries.push(`  ${JSON.stringify(key)}: m${i},`)
  })

  lines.push(
    "",
    "export const staticFiles: Record<string, string> = {",
    ...staticEntries,
    "}",
    "",
    "export const migrationFiles: Record<string, string> = {",
    ...migrationEntries,
    "}",
    ""
  )

  writeFileSync(EMBEDS_PATH, lines.join("\n"))
  console.log(
    `Embedded ${staticPaths.length} frontend files + ${migrationPaths.length} migration files`
  )
}

console.log("Building frontend…")
const build = Bun.spawn(["bun", "run", "build"], {
  cwd: ROOT,
  stdout: "inherit",
  stderr: "inherit",
  stdin: "inherit",
})
const buildCode = await build.exited
if (buildCode !== 0) {
  console.error("Frontend build failed")
  process.exit(buildCode)
}

try {
  genEmbeds()

  console.log(`Compiling standalone binary → ${OUTFILE}`)
  const result = await Bun.build({
    entrypoints: [join(ROOT, "server", "index.ts")],
    compile: {
      outfile: OUTFILE,
    },
  })

  if (!result.success) {
    console.error("Compile failed:")
    for (const log of result.logs) console.error(log)
    process.exit(1)
  }

  const built = result.outputs[0]?.path ?? OUTFILE
  console.log(`Done: ${built}`)
  console.log("Run it with: .\\release\\app-runner.exe   (or ./release/app-runner)")
} finally {
  writeFileSync(EMBEDS_PATH, STUB)
}
